// Builds renderer/lib/icons.js from Lucide (https://lucide.dev, ISC licence) — run after updating lucide-static:
//   node tools/make-icons.js
// Solaris icon name → Lucide icon name. Brand icons Lucide doesn't ship (Discord) stay hand-made in core.js.
const fs = require('fs');
const path = require('path');

const MAP = {
  logout: 'log-out', home: 'house', library: 'library', browse: 'compass', sun: 'orbit', servers: 'server', skins: 'shirt',
  gallery: 'images', console: 'terminal', changelog: 'scroll-text', roadmap: 'map', settings: 'settings', play: 'play',
  stop: 'square', plus: 'plus', search: 'search', folder: 'folder', trash: 'trash-2', copy: 'copy', download: 'download',
  upload: 'upload', share: 'share-2', star: 'star', more: 'ellipsis', back: 'chevron-left', fwd: 'chevron-right',
  close: 'x', min: 'minus', max: 'square', check: 'check', refresh: 'refresh-cw', alert: 'triangle-alert', shield: 'shield',
  globe: 'globe', user: 'user', users: 'users', world: 'earth', box: 'box', palette: 'palette', cpu: 'cpu', key: 'key-round',
  hdd: 'hard-drive', link: 'link', info: 'info', zap: 'zap', layers: 'layers', edit: 'pencil', image: 'image', file: 'file',
  external: 'external-link', heart: 'heart', eye: 'eye', bug: 'bug', chart: 'chart-column', clock: 'clock',
  calendar: 'calendar', list: 'list', grid: 'layout-grid', sort: 'arrow-up-down', wifi: 'wifi',
  // new in 1.4
  host: 'radio-tower', power: 'power', send: 'send', sliders: 'sliders-horizontal', sparkles: 'sparkles', package: 'package-check',
};

const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const inner = (name) => {
  const svg = fs.readFileSync(path.join(dir, name + '.svg'), 'utf8');
  return svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
};
const out = {};
for (const [k, v] of Object.entries(MAP)) out[k] = inner(v);
out.starFill = inner('star').replace('<path ', '<path fill="currentColor" ');
const version = require('lucide-static/package.json').version;
const js = `/* Icons from Lucide ${version} (https://lucide.dev) — ISC License, Copyright (c) Lucide Contributors.\n   Generated by tools/make-icons.js — do not edit by hand. */\nObject.assign(ICONS, ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')});\n`;
fs.writeFileSync(path.join(__dirname, '..', 'renderer', 'lib', 'icons.js'), js);
console.log('icons.js written:', Object.keys(out).length, 'icons from Lucide', version);
